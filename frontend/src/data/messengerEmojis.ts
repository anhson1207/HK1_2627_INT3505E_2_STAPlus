export function getRecentEmojis(): EmojiItem[] {
    try {
        const raw = localStorage.getItem(RECENT_STORAGE_KEY);
        if (!raw) return [];
        const parsed = JSON.parse(raw);
        if (!Array.isArray(parsed)) return [];
        const allMap = new Map<string, EmojiItem>();
        for (const cat of EMOJI_CATEGORIES) {
            for (const item of cat.emojis) {
                if (!allMap.has(item.char)) {
                    allMap.set(item.char, item);
                }
            }
        }
        return parsed
            .filter((item): item is string => typeof item === "string" && item.length > 0)
            .slice(0, MAX_RECENT_EMOJIS)
            .map((char) => allMap.get(char) ?? e(char, char));
    } catch {
        return [];
    }
}

export function recordRecentEmoji(char: string): EmojiItem[] {
    try {
        const current = getRecentEmojis().map((item) => item.char);
        const next = [char, ...current.filter((item) => item !== char)].slice(0, MAX_RECENT_EMOJIS);
        localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(next));
    } catch {
        // Ignore storage errors
    }
    return getRecentEmojis();
}
